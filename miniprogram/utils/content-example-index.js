export function hasKnownContentExamples(wordId, topicIds = []) {
  const id = String(wordId || '').trim();
  if (!id) return false;

  const topics = Array.isArray(topicIds) && topicIds.length ? topicIds : Object.keys(TOPIC_WORD_INDEX);
  return topics.some((topicId) => {
    const topicIndex = TOPIC_WORD_INDEX[topicId];
    // Unknown topics are allowed to fetch so future corpora are not accidentally hidden.
    if (!topicIndex) return true;
    return Boolean(topicIndex[id]);
  });
}
